type Draft = Omit<Letter, 'id' | 'tpl' | 'day'>;

interface MailDef {
  id: string;
  /** Сюжетное письмо: приходит один раз, когда выполнено условие. */
  story?: boolean;
  /** Продолжение цепочки: приходит только как ответ на другое письмо. */
  follow?: boolean;
  /** Ключ «уже приходило» (по умолчанию id) — например, раз в год. */
  key?: (g: GameState) => string;
  /** Для сюжетных — повод, для обычных — можно ли прислать сейчас. */
  when?: (g: GameState) => boolean;
  weight?: number;
  make: (g: GameState, vals: number[]) => Draft | null;
  /** Ответ на письмо: применяет последствия и возвращает, чем всё кончилось. */
  answer?: (g: GameState, L: Letter, opt: number) => string;
}

// ---------- помощники ----------
const C = (g: GameState) => g.countries[g.player];
const S = (g: GameState) => STATS[g.player];
const land = (g: GameState) => COUNTRY_DEFS[g.player].name;
const cap = (g: GameState) => REGIONS[C(g).capital]?.name ?? 'столица';
const inc = (g: GameState) => Math.max(20, S(g).taxIncome);
const brains = (g: GameState) => Math.max(5, S(g).brainsRate);
const food = (g: GameState) => Math.max(1, S(g).foodCons);
const myRegion = (g: GameState) => {
  const r = S(g).regions;
  return REGIONS[r.length ? pick(g, r) : C(g).capital]?.name ?? cap(g);
};
const coastal = (g: GameState) => S(g).regions.some((r) => REGIONS[r].coastal);
const cname = (i: number) => COUNTRY_DEFS[i]?.name ?? '?';
const hello = (g: GameState) =>
  ({ democracy: 'Здравствуйте, президент!', republic: 'Здравствуйте, президент!', monarchy: 'Ваше Величество!', dictatorship: 'Здравствуйте, Вождь!' })[C(g).gov];
const bots = (g: GameState) => g.countries.filter((c) => c.alive && c.idx !== g.player).map((c) => c.idx);
const botBy = (g: GameState, ok: (i: number) => boolean) => {
  const b = bots(g).filter(ok);
  return b.length ? pick(g, b) : -1;
};
function mod(g: GameState, kind: TempMod['kind'], value: number, days: number, label: string) {
  C(g).mods.push({ kind, value, until: g.day + days, label });
}
const stab = (g: GameState, v: number, days: number, label: string) => mod(g, 'stab', v, days, label);
const pay = (g: GameState, v: number) => { C(g).money -= v; };
const relAll = (g: GameState, v: number) => bots(g).forEach((i) => addRel(g, g.player, i, v));
/** Регион, где стоит здание этого типа (или любой свой). */
function regionWith(g: GameState, type: string): string {
  for (const key in g.buildings) {
    const b = g.buildings[+key];
    if (b.type === type && g.regions[REGION_OF[+key]].owner === g.player) return REGIONS[REGION_OF[+key]].name;
  }
  return myRegion(g);
}
function calendar(day: number) {
  const d = new Date(Date.UTC(START_YEAR, 0, 1) + Math.floor(day) * 86400000);
  return { year: d.getUTCFullYear(), month: d.getUTCMonth(), date: d.getUTCDate() };
}
/** Отложенное письмо-продолжение. */
function later(g: GameState, tpl: string, days: number, vals: number[] = [], target?: number) {
  (g.mailQueue ??= []).push({ day: g.day + days, tpl, vals, target });
}

