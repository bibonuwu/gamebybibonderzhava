const BY_ID: Record<string, MailDef> = Object.fromEntries(MAIL.map((m) => [m.id, m]));
const MAIL_MAX = 40;

/** Положить письмо в ящик. */
function deliver(g: GameState, def: MailDef, vals: number[] = [], target?: number): boolean {
  const d = def.make(g, vals);
  if (!d) return false;
  const L: Letter = { ...d, id: g.nextId++, tpl: def.id, day: g.day };
  if (target !== undefined) L.target ??= target;
  if (vals.length) L.vals ??= vals;
  g.mail.unshift(L);
  // ящик не бесконечный: выкидываем самые старые прочитанные
  while (g.mail.length > MAIL_MAX) {
    let k = g.mail.length - 1;
    while (k > 0 && (!g.mail[k].read || (g.mail[k].gift && !g.mail[k].claimed))) k--;
    g.mail.splice(k > 0 ? k : g.mail.length - 1, 1);
  }
  g.counters.lastMail = g.day;
  g.counters.letters = (g.counters.letters ?? 0) + 1;
  sfx('mail');
  return true;
}

/** Раз в день: продолжения цепочек, сюжетные письма, иногда — обычные. */
export function tickMail(g: GameState) {
  const q = g.mailQueue;
  if (q?.length) {
    const due = q.findIndex((m) => m.day <= g.day);
    if (due >= 0) {
      const m = q.splice(due, 1)[0];
      const def = BY_ID[m.tpl];
      if (def) deliver(g, def, m.vals, m.target);
      return;
    }
  }
  const since = g.day - (g.counters.lastMail ?? -99);
  if (since < 5) return;
  if (g.day % 2 === 0) {
    for (const def of MAIL) {
      if (!def.story) continue;
      const key = def.key?.(g) ?? def.id;
      if (g.mailSeen.includes(key) || !def.when!(g)) continue;
      g.mailSeen.push(key);
      if (deliver(g, def)) return;
    }
  }
  if (g.day < g.nextMailDay) return;
  g.nextMailDay = g.day + 40 + Math.floor(rand(g) * 45);
  // обычное письмо: не то же, что недавно
  const recent = new Set(g.mail.slice(0, 8).map((l) => l.tpl));
  const pool = MAIL.filter((m) => !m.story && !m.follow && !recent.has(m.id) && (!m.when || m.when(g)));
  if (!pool.length) return;
  let x = rand(g) * pool.reduce((s, m) => s + (m.weight ?? 1), 0);
  for (const m of pool) {
    x -= m.weight ?? 1;
    if (x <= 0) {
      deliver(g, m);
      return;
    }
  }
}

export const unreadMail = (g: GameState) => g.mail.filter((l) => !l.read).length;

export function readLetter(g: GameState, id: number) {
  const L = g.mail.find((l) => l.id === id);
  if (L) L.read = true;
}

/** Описание вложения для интерфейса. */
export function giftParts(gift: LetterGift): string[] {
  const out: string[] = [];
  if (gift.money) out.push(`💰 +${fmt(gift.money)}`);
  if (gift.brains) out.push(`🧠 +${fmt(gift.brains)}`);
  if (gift.food) out.push(`🌾 +${fmt(gift.food)} т`);
  if (gift.stab) out.push(`⚖️ +${gift.stab}`);
  return out;
}

/** Забрать вложение. null — успех. */
export function claimLetter(g: GameState, id: number): string | null {
  const L = g.mail.find((l) => l.id === id);
  if (!L?.gift) return 'В письме ничего нет';
  if (L.claimed) return 'Подарок уже забран';
  const c = C(g);
  const gift = L.gift;
  if (gift.money) c.money += gift.money;
  if (gift.brains) c.brains += gift.brains;
  if (gift.food) c.food += gift.food;
  if (gift.stab) stab(g, gift.stab, 180, gift.label);
  L.claimed = true;
  sfx('coins');
  log(g, `🎁 ${gift.label}: ${giftParts(gift).join(', ')}`, 'good', false);
  computeAll(g);
  return null;
}

/** Ответить на письмо. null — успех. */
export function answerLetter(g: GameState, id: number, opt: number): string | null {
  const L = g.mail.find((l) => l.id === id);
  const def = L && BY_ID[L.tpl];
  if (!L || !def?.answer || !L.replies?.[opt]) return 'На это письмо нельзя ответить';
  if (L.answered !== undefined) return 'Вы уже ответили';
  L.answered = opt;
  L.result = def.answer(g, L, opt);
  L.read = true;
  sfx('notify');
  log(g, `✉️ Ответ на письмо «${L.subject}»: ${L.replies[opt].label}`, 'info', false);
  computeAll(g);
  return null;
}
